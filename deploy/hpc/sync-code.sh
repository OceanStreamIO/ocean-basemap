#!/usr/bin/env bash
# =============================================================================
# Send this repository's source to the cluster
# =============================================================================
# The compute cluster cannot reach a git remote, so source arrives as a tar
# stream. rsync is not used: it is absent from the container this runs in.
#
# Only source is sent. The virtual environment, the staged inputs and the
# rendered output on the cluster are left alone.
#
#   ./deploy/hpc/sync-code.sh              # send and reinstall the package
#   ./deploy/hpc/sync-code.sh --dry-run    # list what would go
# =============================================================================
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=deploy/hpc/lib.sh
. "$SCRIPT_DIR/lib.sh"

DRY_RUN=0
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1
[ "${1:-}" = "-h" ] || [ "${1:-}" = "--help" ] && { sed -n '2,14p' "$0" >&2; exit 0; }

require_cmd git tar
PATHS="src pyproject.toml uv.lock color-ramps lake-sources.json lake-depths.json"
DEST="$HPC_ROOT/code"

cd "$PROJECT_DIR"
if [ "$DRY_RUN" = "1" ]; then
    log "Would send to $DEST"
    # shellcheck disable=SC2086
    tar -cf - --exclude='__pycache__' --exclude='*.pyc' $PATHS | tar -tf - | head -20 >&2
    exit 0
fi

require_site
require_hpc_key
REV="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
DIRTY=""
git diff --quiet HEAD -- src 2>/dev/null || DIRTY=" (with uncommitted changes in src/)"

log "Sending $REV$DIRTY to $DEST"
# shellcheck disable=SC2086
hpc_send_tree "$PROJECT_DIR" "$DEST" --exclude='__pycache__' --exclude='*.pyc' $PATHS

# Put the package on the path with a .pth file rather than installing it.
#
# `pip install -e .` would need the build backend this project declares, and that
# is a build dependency: it is not in the wheelhouse, because the wheelhouse is
# the runtime closure, and it cannot be fetched because there is no index to fetch
# it from. A path file is what an editable install leaves behind anyway, and it
# means a code sync is a copy and nothing else -- no build, no network, and
# nothing that can half-succeed.
hpc_ssh_login "
    set -e
    # The module has to come first. The virtual environment's interpreter is
    # dynamically linked against the module's libpython, so activating without
    # loading it gives 'cannot open shared object file libpython3.12.so' -- which
    # reads like a broken environment and is only a missing LD_LIBRARY_PATH.
    module load $(hpc_modules "$HPC_MODULES")
    . '$HPC_VENV/bin/activate'
    unset PYTHONHOME PYTHONPATH
    site=\$(python -c 'import sysconfig; print(sysconfig.get_paths()[\"purelib\"])')
    echo '$DEST/src' > \"\$site/basemap.pth\"

    # The path file puts the package on the path; it does not create the console
    # script, which a real install would have generated from the project's
    # entry point. The batch templates call \`oceanbase\`, so write it.
    mkdir -p '$HPC_BIN'
    printf '%s\n' '#!/bin/bash' \
        '# Generated by deploy/hpc/sync-code.sh -- do not edit.' \
        'exec \"$HPC_VENV/bin/python\" -m basemap.cli \"\$@\"' > '$HPC_BIN/oceanbase'
    chmod +x '$HPC_BIN/oceanbase'
    PATH='$HPC_BIN':\$PATH oceanbase --help >/dev/null \
        && echo '    oceanbase runs' || { echo '    oceanbase is broken'; exit 1; }
    echo '$REV  '\$(date -u +%FT%TZ) >> '$DEST/.synced-revisions'
    python -c 'import basemap, basemap.pipeline.xyz as x; print(\"    basemap importable, tree =\", f\"{x.Shard().expected_tiles(x.MAX_ZOOM):,}\", \"tiles\")'
" || fail "could not install the package"
ok "Synced at $REV"
