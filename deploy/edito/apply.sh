#!/usr/bin/env bash
# =============================================================================
# apply.sh — publish the basemap viewer on EDITO
# =============================================================================
# Builds no image. The viewer is three static files served by stock nginx, so
# the assets ship as a ConfigMap that is regenerated from src/basemap/viewer/
# on every run. Tiles are never proxied through the pod — the browser fetches
# them directly from the object store, which is why TILE_BASE must be a public,
# CORS-enabled URL.
#
#   ./deploy/edito/apply.sh              # publish, pointing at the S3 bucket
#   ./deploy/edito/apply.sh --dry-run    # server-side validation only
#
# Overridable: NAMESPACE, HOST, TILE_BASE, PMTILES_BASE.
# =============================================================================
set -euo pipefail

NAMESPACE="${NAMESPACE:-project-oceanstream}"
HOST="${HOST:-project-oceanstream-basemap.lab.dive.edito.eu}"
TILE_BASE="${TILE_BASE:-https://oceanstream-bucket.s3.waw3-1.cloudferro.com/basemap}"
# upload_s3.py writes PMTiles under <prefix>/tiles/ but hillshade under
# <prefix>/hillshade/, so the two bases differ by that one segment.
PMTILES_BASE="${PMTILES_BASE:-${TILE_BASE}/tiles}"

EDITO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VIEWER_DIR="$(cd "$EDITO_DIR/../../src/basemap/viewer" && pwd)"

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

info() { printf '\033[1;34m▶ %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m  ✓ %s\033[0m\n' "$*"; }
err()  { printf '\033[1;31m✖ %s\033[0m\n' "$*" >&2; exit 1; }

command -v kubectl >/dev/null || err "kubectl not found"
[[ -f "$VIEWER_DIR/index.html" ]] || err "viewer assets not found at $VIEWER_DIR"

# ---------------------------------------------------------------------------
# Assets ConfigMap, with config.js rewritten to point at the published tiles.
# ---------------------------------------------------------------------------
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

cp "$VIEWER_DIR/index.html" "$VIEWER_DIR/app.js" "$VIEWER_DIR/style.css" "$STAGE/"
cat > "$STAGE/config.js" <<EOF
// Generated by deploy/edito/apply.sh — do not edit in the cluster.
window.BASEMAP_TILE_BASE    = '${TILE_BASE}';
window.BASEMAP_PMTILES_BASE = '${PMTILES_BASE}';
EOF

info "Tile base   : $TILE_BASE"
info "PMTiles base: $PMTILES_BASE"

KUBECTL=(kubectl -n "$NAMESPACE")
APPLY=("${KUBECTL[@]}" apply)
if (( DRY_RUN )); then
    APPLY+=(--dry-run=server)
    info "DRY RUN — nothing will be changed"
fi

info "Applying assets ConfigMap"
"${KUBECTL[@]}" create configmap basemap-viewer-assets \
    --from-file="$STAGE" --dry-run=client -o yaml | "${APPLY[@]}" -f -
ok "basemap-viewer-assets"

info "Applying Deployment, Service and Ingress"
"${APPLY[@]}" -f "$EDITO_DIR/10-viewer.yaml" -f "$EDITO_DIR/11-viewer-ingress.yaml"

if (( DRY_RUN )); then
    ok "Dry run passed"
    exit 0
fi

# subPath mounts do not pick up ConfigMap changes, so a restart is mandatory
# whenever the assets change — not merely a convenience.
info "Restarting to pick up the new assets"
"${KUBECTL[@]}" rollout restart deployment/basemap-viewer >/dev/null
"${KUBECTL[@]}" rollout status deployment/basemap-viewer --timeout=120s

ok "Published at https://${HOST}"
echo
echo "Point it elsewhere without redeploying:"
echo "  https://${HOST}/?base=<tiles-url>&pmtiles=<pmtiles-url>"
