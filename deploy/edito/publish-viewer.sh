#!/usr/bin/env bash
# =============================================================================
# publish-viewer.sh — put the viewer on the bucket, beside the tiles
# =============================================================================
# The viewer that runs on EDITO lives in this project's namespace and goes with
# it. This copy is four static files next to the archives they read: no server
# to stop, and the link keeps working as long as object storage does. It is
# also what the Helm chart fetches at start-up.
#
#   ./deploy/edito/publish-viewer.sh
#   ./deploy/edito/publish-viewer.sh --dry-run
#
# The layout matches the deployment's -- index.html at the top, everything else
# under static/ -- which is why the page's asset paths are relative: the same
# files work at a site's root and under a prefix.
# =============================================================================
set -euo pipefail

BUCKET="${BASEMAP_S3_BUCKET:-oceanstream-bucket}"
ENDPOINT="${BASEMAP_S3_ENDPOINT:-https://s3.waw3-1.cloudferro.com}"
PREFIX="${BASEMAP_VIEWER_PREFIX:-basemap/viewer}"
# shellcheck source=deploy/edito/tile-base.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/tile-base.sh"
TILE_BASE="$(resolve_tile_base)"
VIEWER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../src/basemap/viewer" && pwd)"

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

info() { printf '\033[1;34m▶ %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m  ✓ %s\033[0m\n' "$*"; }

# The endpoint compresses nothing and cannot be told to, so the files are
# stored compressed with the header that says so: 92 KB of JavaScript, CSS and
# HTML becomes 27 KB. Only the viewer's own files, which no one reads but a
# browser -- the archives and style.json are left alone, because a client that
# does not ask for gzip would get bytes it cannot read.
#
# AWS_REQUEST_CHECKSUM_CALCULATION matters more than it looks. Without it the
# CLI streams the upload and appends its own encoding, so the object comes back
# as "content-encoding: gzip,aws-chunked", which no browser can decode: the
# page loads, the script does not, and nothing says why.
put() {  # file, key, content-type
    if (( DRY_RUN )); then
        ok "would put $2 (gzipped)"
        return
    fi
    local gz; gz="$(mktemp)"
    gzip -9 -c "$1" > "$gz"
    AWS_REQUEST_CHECKSUM_CALCULATION=when_required \
    aws --endpoint-url "$ENDPOINT" s3 cp "$gz" "s3://$BUCKET/$2" \
        --content-type "$3" --content-encoding gzip \
        --cache-control "public, max-age=300" --only-show-errors
    rm -f "$gz"
    ok "$2"
}

info "Viewer → s3://$BUCKET/$PREFIX"
put "$VIEWER_DIR/index.html" "$PREFIX/index.html" text/html
put "$VIEWER_DIR/app.js" "$PREFIX/static/app.js" application/javascript
put "$VIEWER_DIR/style.css" "$PREFIX/static/style.css" text/css
put "$VIEWER_DIR/globe.html" "$PREFIX/static/globe.html" text/html
put "$VIEWER_DIR/cesium-provider.js" "$PREFIX/static/cesium-provider.js" application/javascript
# The plain-tiles viewer: no PMTiles, one raster source, for anyone checking
# the {z}/{x}/{y} endpoint works before wiring it into their own map.
put "$VIEWER_DIR/xyz.html" "$PREFIX/static/xyz.html" text/html

# The tile origin is configuration, not source: the deployment writes its own
# and so does the chart, so this copy gets one too.
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
cat > "$tmp" <<CONFIG
// Generated by deploy/edito/publish-viewer.sh — do not edit in the bucket.
window.BASEMAP_TILE_BASE    = '$TILE_BASE';
window.BASEMAP_PMTILES_BASE = '$TILE_BASE/tiles';
CONFIG
# shellcheck source=deploy/edito/tile-versions.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/tile-versions.sh"
tile_versions_js "$TILE_BASE/tiles" >> "$tmp"
put "$tmp" "$PREFIX/static/config.js" application/javascript

# These five files are published under fixed names, so the CDN holds a copy
# that a new upload does not disturb. The ?v= in index.html busts a browser's
# cache but not the edge's -- query strings are not in the cache key -- so the
# edge has to be told explicitly. Best effort: a bucket publish that worked
# should not be reported as failed because AWS credentials are absent.
"$(cd "$(dirname "${BASH_SOURCE[0]}")/../cdn" && pwd)/invalidate.sh" \
    "/$PREFIX/*" "/basemap/style.json" || true

echo
echo "Open it at:"
echo "  https://$BUCKET.${ENDPOINT#https://}/$PREFIX/index.html"
